/// Шаблон для .agent/workflows/agent.md
pub const WORKFLOW_AGENT: &str = r#"# Рабочий процесс для агента

1. Прочитай `README.md`, `concept.md`, `tech_stack.md`, `rules.md`.
2. Проверь `tasks/in_progress/`. Если есть задача – работай над ней. Если нет – возьми первую из `tasks/todo/` и перемести в `in_progress/`.
3. Перед началом реализации задачи прочитай `struct.md` (если есть) и соответствующие `specs/`.
4. После выполнения:
   - Обнови файл задачи (добавь дату завершения).
   - Перемести его в `tasks/done/`.
   - Сделай коммит с сообщением `feat: #задача описание`.
   - Если нужен PR – создай его и запроси ревью.
5. Для Git-операций следуй `workflows/git.md`.
"#;

/// Шаблон для .agent/workflows/git.md
pub const WORKFLOW_GIT: &str = r#"# Git-процесс

## Формат коммитов

- feat: добавление новой функциональности
- fix: исправление ошибок
- docs: обновление документации
- refactor: рефакторинг кода
- test: добавление тестов
- chore: рутинные задачи (обновление зависимостей)

## Структура веток

- main: основная ветка
- develop: разработка
- feature/*: новые фичи
- fix/*: исправления

## PR Process

1. Создай ветку из develop
2. Сделай коммиты с описательными сообщениями
3. Отправь PR в develop
4. Попроси ревью
5. После слияния удали ветку
"#;

