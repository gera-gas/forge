/// Шаблон для forge-src/workflows/agent.md
pub const WORKFLOW_AGENT: &str = r#"# Рабочий процесс для агента

1. Прочитай `README.md`, `concept.md`, `tech_stack.md`, `rules.md`.
2. Проверь `kanban/4_in_progress/`. Если есть задача – работай над ней. Если нет – возьми первую из `kanban/3_todo/` и перемести в `4_in_progress/`.
3. Перед началом реализации задачи прочитай `struct.md` (если есть) и соответствующий дизайн в `kanban/2_design/<design_id>/`.
4. После выполнения:
   - Перемести задачу в `kanban/5_done/` (completed_at запишется автоматически).
   - Сделай коммит с сообщением `task(<id>): complete`.
   - Если нужен PR – создай его и запроси ревью.
5. Для Git-операций следуй `workflows/git.md`.

## Правило: привязка задач к дизайну

**Каждая задача в `3_todo/` и далее должна иметь поле `design` в frontmatter**, указывающее на ID дизайна в `2_design/` из которого она порождена.

Пример:
```yaml
---
id: "003"
title: "Рефакторинг TaskCommands"
design: "001"        # ← ID дизайна в 2_design/001/
type: "feature"
priority: "high"
---
```

При создании задачи через CLI:
```bash
forge task new "Название задачи" --design 001
```

При перемещении задачи в `3_todo/` без указания дизайна — агент должен предупредить:
> ⚠️ Задача не привязана к дизайну. Рекомендуется указать `--design <id>`.

## Команды для работы с kanban

- `forge task new "Название"` — создать задачу в sketch
- `forge task new "Название" --design 001` — создать задачу с привязкой к дизайну
- `forge task move <id> <stage>` — переместить задачу
- `forge task list` — список всех задач
- `forge task list --design 001` — задачи конкретного дизайна
- `forge task show <id>` — детали задачи
"#;

/// Шаблон для forge-src/workflows/git.md
pub const WORKFLOW_GIT: &str = r#"# Git-процесс

## Формат коммитов

- feat: добавление новой функциональности
- fix: исправление ошибок
- docs: обновление документации
- refactor: рефакторинг кода
- test: добавление тестов
- chore: рутинные задачи (обновление зависимостей)

## Структура веток

- main: основная ветка
- develop: разработка
- feature/*: новые фичи
- fix/*: исправления

## PR Process

1. Создай ветку из develop
2. Сделай коммиты с описательными сообщениями
3. Отправь PR в develop
4. Попроси ревью
5. После слияния удали ветку
"#;

